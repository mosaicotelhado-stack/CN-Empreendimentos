  function abrirLightbox(src, titulo, descricaoTecnica) {
    var modal = document.getElementById("lightbox-cn");
    if (!modal) {
      modal = document.createElement("div");
      modal.id = "lightbox-cn";
      modal.className = "lightbox-modal";
      modal.innerHTML =
        '<div class="lightbox-conteudo" id="lightbox-box">' +
        '<img id="lightbox-img" src="" alt="">' +
        '<div id="lightbox-titulo" class="lightbox-titulo"></div>' +
        '<hr class="divisor-amarelo">' +
        '<p id="lightbox-descricao" class="lightbox-descricao"></p>' +
        '<div class="lightbox-fechar-aviso">Clique fora da caixa para fechar</div>' +
        "</div>";
      modal.addEventListener("click", function (evento) {
        if (evento.target === modal) {
          modal.classList.remove("aberto");
        }
      });
      document.body.appendChild(modal);
    }
    document.getElementById("lightbox-img").src = src;
    document.getElementById("lightbox-img").alt = titulo;
    document.getElementById("lightbox-titulo").textContent = titulo;
    document.getElementById("lightbox-descricao").textContent = descricaoTecnica || "";
    modal.classList.add("aberto");
  }

