  function pegarServicoDaUrl() {
    var busca = window.location.search;
    if (!busca) return null;
    var parametros = new URLSearchParams(busca);
    var chave = parametros.get("servico");
    return catalogoServicos[chave] ? chave : null;
  }

  function criarImagemSegura(src, alt, textoFallback) {
    var img = document.createElement("img");
    img.src = src;
    img.alt = alt;
    img.onerror = function () {
      var box = document.createElement("div");
      box.className = "foto-fallback";
      box.textContent = textoFallback;
      if (img.parentNode) {
        img.parentNode.replaceChild(box, img);
      }
    };
    return img;
  }

